// Fetches the real favicons of every host referenced in src/lib/demo-profiles.ts
// and rewrites src/lib/demo-favicons.ts with data URLs.
// Run this when the demo bookmark list changes. Demo favicons are bundled so the
// web preview renders real site icons with no network requests at runtime.
import { Buffer } from 'node:buffer'
import { readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const SOURCE = path.resolve('src/lib/demo-profiles.ts')
const OUTPUT = path.resolve('src/lib/demo-favicons.ts')
const TIMEOUT_MS = 15_000
const SOURCES_HEAD = '// GENERATED by scripts/fetch-demo-favicons.mjs — do not edit by hand.\n// Run the script again when demo bookmarks change.\n'

function hostsFromSource(source) {
  const urls = source.match(/https?:\/\/[^'"\s)]+/g) ?? []
  const hosts = new Set()
  for (const raw of urls) {
    try {
      const host = new URL(raw).hostname.replace(/^www\./, '').toLowerCase()
      if (host)
        hosts.add(host)
    }
    catch {
      // Skip URLs that do not parse; the demo data is validated by tests anyway.
    }
  }
  return [...hosts].sort()
}

async function fetchImage(url) {
  const response = await fetch(url, {
    signal: AbortSignal.timeout(TIMEOUT_MS),
    redirect: 'follow',
  })
  if (!response.ok)
    throw new Error(`HTTP ${response.status}`)
  const contentType = (response.headers.get('content-type') ?? '').split(';')[0].trim()
  if (!contentType.startsWith('image/'))
    throw new Error(`unexpected content-type "${contentType}"`)
  const body = Buffer.from(await response.arrayBuffer())
  if (body.length < 100)
    throw new Error('icon is too small to be real')
  return { contentType, body }
}

/** Google’s favicon cache serves the real site icon; used only at generation time. */
function sources(host) {
  return [
    `https://www.google.com/s2/favicons?domain=${encodeURIComponent(host)}&sz=128`,
    `https://${host}/favicon.ico`,
  ]
}

const source = await readFile(SOURCE, 'utf8')
const hosts = hostsFromSource(source)
console.log(`Found ${hosts.length} hosts in ${path.basename(SOURCE)}`)

const results = new Map()
const failures = []
for (const host of hosts) {
  let found = null
  for (const candidate of sources(host)) {
    try {
      found = await fetchImage(candidate)
      break
    }
    catch (error) {
      found = null
      void error
    }
  }
  if (found) {
    results.set(host, `data:${found.contentType};base64,${found.body.toString('base64')}`)
    console.log(`ok   ${host} (${Math.round(found.body.length / 1024)} KB, ${found.contentType})`)
  }
  else {
    failures.push(host)
    console.warn(`MISS ${host} (will render the fallback globe)`)
  }
}

const entries = [
  ...results.entries(),
]
  .map(([host, dataUrl]) => `  '${host}': '${dataUrl}',`)
  .join('\n')

const output = `${SOURCES_HEAD}// Real favicons for the seeded demo profiles. Bundled so the web preview
// renders real site icons with no network requests at runtime.
// The installed extension is unaffected and uses the browser's favicon cache.
declare global {
  interface Window {
    chrome?: { runtime?: { getURL?: (path: string) => string } }
    browser?: { runtime?: { getURL?: (path: string) => string } }
  }
}

export const DEMO_FAVICONS: Readonly<Record<string, string>> = {
${entries}
}

export function demoFaviconFor(pageUrl: string): string | undefined {
  try {
    const host = new URL(pageUrl).hostname.replace(/^www\\./, '').toLowerCase()
    return DEMO_FAVICONS[host]
  }
  catch {
    return undefined
  }
}

/**
 * True only in the web preview: no extension runtime is present.
 * The installed extension is unaffected and uses the browser's own favicon cache.
 */
export function demoFaviconsAvailable(): boolean {
  if (typeof window === 'undefined')
    return false
  return !window.chrome?.runtime?.getURL && !window.browser?.runtime?.getURL
}
`

await writeFile(OUTPUT, output)
const totalKb = [
  ...results.values(),
].reduce((sum, url) => sum + url.length, 0) / 1024
console.log(`\nWrote ${OUTPUT}`)
console.log(`${entries.length} favicons, ${Math.round(totalKb)} KB total`)
if (failures.length > 0)
  console.warn(`Missing (${failures.length}): ${failures.join(', ')}`)
process.exit(0)
